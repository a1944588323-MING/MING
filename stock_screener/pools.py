def get_pool_flat(pool_dict):
    """把分主题的字典展平成 [(code, name, theme), ...] 列表,自动去重"""
    seen = set()
    result = []
    for theme, stocks in pool_dict.items():
        for code, name in stocks.items():
            if code not in seen:
                seen.add(code)
                result.append((code, name, theme))
    return result


